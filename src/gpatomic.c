#define GP_ATOMIC_OP_TEMPLATE(NAME, POSTFIX, GPT, T, OP) \
T gp_atomic_##NAME##_##POSTFIX (GPT* a, T c) \
{ \
    GPMutex* mutex = GP_GET_ATOMIC_MUTEX(a); \
    gp_mutex_lock(mutex); \
    T old, new; \
    memcpy(&old, a, sizeof old); \
    new = old; \
    new OP c; \
    memcpy(a, &new, sizeof new); \
    gp_mutex_unlock(mutex); \
    return old; \
}

