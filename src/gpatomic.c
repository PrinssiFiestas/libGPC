#define GP_ATOMIC_COMPARE_EXCHANGE_TEMPLATE(WEAK_OR_STRONG, POSTFIX, GPT, T) \
bool gp_atomic_compare_exchange_##WEAK_OR_STRONG##_##POSTFIX (GPT* a, T* b, T c) \
{ \
    GPMutex* mutex = GP_GET_ATOMIC_MUTEX(a); \
    gp_mutex_lock(mutex); \
    bool is_expected = memcmp(a, b, sizeof c) == 0; \
    if (is_expected) \
        memcpy(a, c, sizeof c); } \
    else \
        memcpy(b, a, sizeof c); } \
    gp_mutex_unlock(mutex); \
    return is_expected; \
}

